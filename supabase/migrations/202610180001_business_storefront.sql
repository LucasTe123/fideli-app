alter table public.businesses add column if not exists whatsapp_phone text not null default '';

create table if not exists public.storefront_products (
  business_id uuid not null references public.businesses(id) on delete cascade,
  id text not null,
  name text not null,
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (business_id, id)
);

create table if not exists public.storefront_orders (
  business_id uuid not null references public.businesses(id) on delete cascade,
  id text not null,
  customer_name text not null,
  customer_phone text not null default '',
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'nuevo' check (status in ('nuevo','confirmado','entregado','cancelado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (business_id, id)
);

create index if not exists storefront_products_business_idx
  on public.storefront_products (business_id, active);
create index if not exists storefront_orders_business_idx
  on public.storefront_orders (business_id, created_at desc);

alter table public.storefront_products enable row level security;
alter table public.storefront_orders enable row level security;

revoke all on table public.storefront_products, public.storefront_orders from anon;
grant select, insert, update, delete on table public.storefront_products, public.storefront_orders to authenticated;

drop policy if exists "business members manage storefront products" on public.storefront_products;
create policy "business members manage storefront products" on public.storefront_products
  for all using (business_id in (select business_id from public.business_members where user_id = auth.uid()))
  with check (business_id in (select business_id from public.business_members where user_id = auth.uid()));

drop policy if exists "business members manage storefront orders" on public.storefront_orders;
create policy "business members manage storefront orders" on public.storefront_orders
  for all using (business_id in (select business_id from public.business_members where user_id = auth.uid()))
  with check (business_id in (select business_id from public.business_members where user_id = auth.uid()));

create or replace function public.get_storefront(p_slug text)
returns jsonb language sql stable security definer set search_path = pg_catalog, public
as $$
  select jsonb_build_object(
    'name', b.name,
    'products', coalesce((
      select jsonb_agg(jsonb_build_object('id', p.id, 'name', p.name, 'description', p.description, 'price', p.price) order by p.created_at)
      from public.storefront_products p where p.business_id = b.id and p.active
    ), '[]'::jsonb)
  )
  from public.businesses b where b.public_slug = p_slug limit 1;
$$;

revoke all on function public.get_storefront(text) from public;
grant execute on function public.get_storefront(text) to anon, authenticated;

-- The order reference is generated by PostgreSQL so the customer cannot
-- choose another order's identifier or claim an unverified code.
drop function if exists public.place_storefront_order(text, text, text, text, jsonb);

create or replace function public.place_storefront_order(
  p_slug text, p_name text, p_phone text, p_items jsonb
) returns jsonb language plpgsql security definer set search_path = pg_catalog, public, extensions
as $$
declare
  b public.businesses%rowtype;
  normalized_items jsonb;
  order_total numeric(12,2);
  order_code text;
  requested_item jsonb;
  quantity_text text;
  item_count integer;
begin
  select * into b from public.businesses where public_slug = p_slug;
  if not found then raise exception 'Local no encontrado'; end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'Escribe tu nombre'; end if;
  if length(regexp_replace(coalesce(b.whatsapp_phone, ''), '[^0-9]', '', 'g')) < 8 then
    raise exception 'Este local aún no configuró su WhatsApp. Inténtalo más tarde.';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' then raise exception 'El carrito no es válido'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'El carrito está vacío'; end if;

  item_count := jsonb_array_length(p_items);
  for requested_item in select value from jsonb_array_elements(p_items) loop
    if jsonb_typeof(requested_item) is distinct from 'object'
      or jsonb_typeof(requested_item->'id') is distinct from 'string'
      or length(trim(coalesce(requested_item->>'id', ''))) = 0 then
      raise exception 'El carrito contiene un producto inválido';
    end if;
    quantity_text := requested_item->>'quantity';
    if jsonb_typeof(requested_item->'quantity') is distinct from 'number'
      or quantity_text !~ '^[0-9]+$'
      or quantity_text::numeric < 1
      or quantity_text::numeric > 99 then
      raise exception 'La cantidad de un producto no es válida';
    end if;
  end loop;

  if (select count(distinct item->>'id') from jsonb_array_elements(p_items) as x(item)) <> item_count then
    raise exception 'El carrito contiene productos repetidos';
  end if;

  with requested as (
    select (item->>'id') as product_id, (item->>'quantity')::integer as quantity
    from jsonb_array_elements(p_items) item
  ), priced as (
    select p.id, p.name, p.price, r.quantity, p.price * r.quantity as line_total
    from requested r join public.storefront_products p on p.id = r.product_id and p.business_id = b.id and p.active
  )
  select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'quantity', quantity, 'price', price, 'line_total', line_total) order by id), sum(line_total), count(*)
  into normalized_items, order_total, item_count from priced;
  if normalized_items is null then raise exception 'No hay productos disponibles'; end if;
  if item_count <> jsonb_array_length(p_items) then
    raise exception 'Uno o más productos ya no están disponibles. Actualiza el catálogo e inténtalo otra vez.';
  end if;

  loop
    order_code := 'ORD-' || upper(encode(gen_random_bytes(5), 'hex'));
    exit when not exists (
      select 1 from public.storefront_orders
      where business_id = b.id and id = order_code
    );
  end loop;

  insert into public.storefront_orders (business_id,id,customer_name,customer_phone,items,total)
  values (b.id,order_code,trim(p_name),trim(coalesce(p_phone,'')),normalized_items,order_total);
  return jsonb_build_object('id',order_code,'total',order_total,'items',normalized_items,'business_name',b.name,'whatsapp_phone',coalesce(b.whatsapp_phone,''));
end;
$$;

revoke all on function public.place_storefront_order(text, text, text, jsonb) from public;
grant execute on function public.place_storefront_order(text, text, text, jsonb) to anon, authenticated;

